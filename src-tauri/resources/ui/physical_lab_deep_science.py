def lattice_vacf_study(
    *, nx: int = 3, ny: int = 3, layers: int = 2, steps: int = 2048,
    dt: float = 0.004, velocity_scale: float = 0.03, seed: int = 20260911,
    stacking: str = "ABA",
) -> dict[str, Any]:
    """Generate a conservative trajectory, VACF, and finite-cell velocity spectrum."""
    np = _np()
    import physical_lab_lattice_dynamics as lattice

    n_steps = max(256, min(int(steps), 8192))
    h = _finite(dt, "dt")
    scale = _finite(velocity_scale, "velocity_scale")
    if not (0.0005 <= h <= 0.02):
        raise ValueError("dt must be in [0.0005, 0.02]")
    if not (0.0 < scale <= 0.25):
        raise ValueError("velocity_scale must be in (0, 0.25]")
    cfg = lattice.LatticeConfig(
        nx=int(nx), ny=int(ny), layers=int(layers), stacking=str(stacking),
        damping=0.0, interlayer_damping=0.0, drive_mode="none", drive_amplitude=0.0,
        stochastic_mode=False, temperature_reduced=0.0, initial_displacement=0.0,
        duration=max(1.0, n_steps * h), samples=max(256, min(n_steps, 20000)), max_step=h,
    )
    model = lattice.build_lattice(cfg)
    n = len(model.positions)
    u = np.zeros((n, 2), dtype=float)
    rng = np.random.default_rng(int(seed))
    v = rng.normal(scale=scale, size=(n, 2))
    # Remove total translational mode to prevent the VACF from being dominated by rigid drift.
    total_mass = float(np.sum(model.masses))
    com_v = np.sum(model.masses[:, None] * v, axis=0) / total_mass
    v -= com_v

    def conservative_force(uu: Any, vv: Any) -> Any:
        return lattice.force_components(
            model, uu, vv, 0.0, include_dissipation=False, include_external=False
        )["total"]

    force = conservative_force(u, v)
    a = force / model.masses[:, None]
    velocities = np.empty((n_steps, n, 2), dtype=float)
    e0 = lattice.potential_energy(model, u) + 0.5 * float(np.sum(model.masses[:, None] * v * v))
    max_energy_drift = 0.0
    energy_trace: list[float] = []
    energy_time: list[float] = []
    energy_stride = max(1, n_steps // 300)
    for index in range(n_steps):
        v_half = v + 0.5 * h * a
        u = u + h * v_half
        force_new = conservative_force(u, v_half)
        a_new = force_new / model.masses[:, None]
        v = v_half + 0.5 * h * a_new
        a = a_new
        velocities[index] = v
        if index % energy_stride == 0 or index == n_steps - 1:
            energy = lattice.potential_energy(model, u) + 0.5 * float(np.sum(model.masses[:, None] * v * v))
            rel = abs(energy - e0) / max(abs(e0), 1e-30)
            max_energy_drift = max(max_energy_drift, rel)
            energy_trace.append(rel); energy_time.append((index + 1) * h)

    series = velocities.reshape(n_steps, -1)
    # Remove each finite trajectory's temporal mean before correlation/spectral estimation.
    series = series - np.mean(series, axis=0, keepdims=True)
    nfft = 1
    while nfft < 2 * n_steps:
        nfft *= 2
    transformed = np.fft.rfft(series, n=nfft, axis=0)
    corr = np.fft.irfft(transformed * np.conjugate(transformed), n=nfft, axis=0)[:n_steps]
    normalization = np.arange(n_steps, 0, -1, dtype=float)[:, None]
    corr = corr / normalization
    vacf = np.mean(corr, axis=1)
    if abs(float(vacf[0])) <= 1e-30:
        raise RuntimeError("zero VACF normalization")
    vacf_norm = vacf / float(vacf[0])

    window = np.hanning(n_steps)[:, None]
    spectrum_complex = np.fft.rfft(series * window, axis=0)
    density = np.mean(np.abs(spectrum_complex) ** 2, axis=1)
    frequencies = np.fft.rfftfreq(n_steps, d=h)
    if density.size:
        density[0] = 0.0
    area = float(np.trapezoid(density, frequencies)) if len(frequencies) > 1 else 0.0
    density_norm = density / area if area > 0 else density
    dominant_index = int(np.argmax(density_norm[1:]) + 1) if density_norm.size > 1 else 0
    zero_cross = None
    signs = np.signbit(vacf_norm)
    changes = np.where(signs[1:] != signs[:-1])[0]
    if changes.size:
        zero_cross = float((changes[0] + 1) * h)
    return _plain({
        "schema": "physical-lab-lattice-vacf-v1",
        "config": {"nx": int(nx), "ny": int(ny), "layers": int(layers), "stacking": str(stacking), "steps": n_steps, "dt": h, "velocity_scale": scale, "seed": int(seed)},
        "lag_time_reduced": np.arange(n_steps, dtype=float) * h,
        "vacf_normalized": vacf_norm,
        "frequency_cycles_per_reduced_time": frequencies,
        "vibrational_spectral_density_normalized": density_norm,
        "dominant_frequency_cycles_per_reduced_time": float(frequencies[dominant_index]),
        "vacf_first_zero_time_reduced": zero_cross,
        "max_relative_energy_drift": max_energy_drift,
        "energy_trace_time_reduced": energy_time,
        "relative_energy_error_trace": energy_trace,
        "boundary": (
            "Finite-cell reduced-unit conservative trajectory. The VACF and velocity spectral density describe this finite model realization; "
            "they are not q-resolved S(q,omega), not phonon lifetimes, not thermal conductivity, and not calibrated graphene frequencies in THz."
        ),
    })


