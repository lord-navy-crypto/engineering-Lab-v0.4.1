def _solar_energy(r: Any, v: Any, masses: Any, gravitational_constant: float) -> float:
    np = _np()
    rr = np.asarray(r, dtype=float); vv = np.asarray(v, dtype=float); m = np.asarray(masses, dtype=float)
    kinetic = 0.5 * float(np.sum(m[:, None] * vv * vv))
    potential = 0.0
    for i in range(len(m)):
        for j in range(i + 1, len(m)):
            if m[i] == 0.0 or m[j] == 0.0:
                continue
            potential -= gravitational_constant * float(m[i] * m[j]) / max(float(np.linalg.norm(rr[i] - rr[j])), 1e-15)
    return kinetic + potential


def _solar_ang_momentum(r: Any, v: Any, masses: Any):
    np = _np()
    return np.sum(np.asarray(masses)[:, None] * np.cross(r, v), axis=0)


def solar_symplectic_comparison(
    *, duration_years: float = 40.0, dt_years: float = 0.01,
    inclination_jupiter_deg: float = 10.0, reference_samples: int = 1000,
) -> dict[str, Any]:
    """Compare pure-Newtonian velocity-Verlet with the existing DOP853 solver."""
    np = _np()
    import physical_lab_solar_system_dynamics as solar

    duration = _finite(duration_years, "duration_years")
    dt = _finite(dt_years, "dt_years")
    if not (1.0 <= duration <= 300.0):
        raise ValueError("duration_years must be in [1, 300]")
    if not (0.001 <= dt <= 0.08):
        raise ValueError("dt_years must be in [0.001, 0.08]")
    config = solar.SolarSystemConfig(
        duration_years=duration,
        samples=max(200, min(int(reference_samples), 5000)),
        inclination_jupiter_deg=float(inclination_jupiter_deg),
        saturn_backreaction=True,
        solar_1pn=False,
        velocity_cross=False,
        radial_drag=False,
        rtol=1e-11,
        atol=1e-13,
        max_step_years=min(0.03, max(dt, 0.005)),
    )
    m = solar.masses(config)
    state0 = solar.initial_state(config)
    r, v = solar._unpack(state0)
    r = np.asarray(r, dtype=float).copy(); v = np.asarray(v, dtype=float).copy()
    steps = int(round(duration / dt))
    dt = duration / steps
    stride = max(1, steps // 1600)
    a = solar.acceleration(r, v, config)
    e0 = _solar_energy(r, v, m, solar.G)
    l0 = _solar_ang_momentum(r, v, m)
    mtotal = float(np.sum(m))
    bary0 = np.sum(m[:, None] * r, axis=0) / mtotal
    times: list[float] = [0.0]
    energy_error: list[float] = [0.0]
    j_radius: list[float] = [float(np.linalg.norm(r[1] - r[0]))]
    s_radius: list[float] = [float(np.linalg.norm(r[2] - r[0]))]
    max_energy = 0.0; max_l = 0.0; max_bary = 0.0
    for step in range(1, steps + 1):
        v_half = v + 0.5 * dt * a
        r = r + dt * v_half
        # Pure Newtonian acceleration is velocity independent. Pass v_half only to the shared API.
        a_new = solar.acceleration(r, v_half, config)
        v = v_half + 0.5 * dt * a_new
        a = a_new
        if step % stride == 0 or step == steps:
            energy = _solar_energy(r, v, m, solar.G)
            rel_e = abs(energy - e0) / max(abs(e0), 1e-30)
            l = _solar_ang_momentum(r, v, m)
            rel_l = float(np.linalg.norm(l - l0)) / max(float(np.linalg.norm(l0)), 1e-30)
            bary = np.sum(m[:, None] * r, axis=0) / mtotal
            bary_drift = float(np.linalg.norm(bary - bary0))
            max_energy = max(max_energy, rel_e); max_l = max(max_l, rel_l); max_bary = max(max_bary, bary_drift)
            times.append(step * dt); energy_error.append(rel_e)
            j_radius.append(float(np.linalg.norm(r[1] - r[0])))
            s_radius.append(float(np.linalg.norm(r[2] - r[0])))

    reference = solar.integrate_case(config)
    ref_r = np.asarray(reference["positions_AU"][-1], dtype=float)
    j_final_difference = float(np.linalg.norm((r[1] - r[0]) - (ref_r[1] - ref_r[0])))
    s_final_difference = float(np.linalg.norm((r[2] - r[0]) - (ref_r[2] - ref_r[0])))
    ref_diag = reference.get("diagnostics") or {}
    return _plain({
        "schema": "physical-lab-solar-symplectic-comparison-v1",
        "duration_years": duration,
        "verlet_dt_years": dt,
        "verlet_steps": steps,
        "time_years": times,
        "verlet_relative_energy_error": energy_error,
        "jupiter_heliocentric_radius_AU": j_radius,
        "saturn_heliocentric_radius_AU": s_radius,
        "verlet_max_relative_energy_drift": max_energy,
        "verlet_max_relative_angular_momentum_drift": max_l,
        "verlet_max_barycenter_drift_AU": max_bary,
        "final_jupiter_position_difference_vs_DOP853_AU": j_final_difference,
        "final_saturn_position_difference_vs_DOP853_AU": s_final_difference,
        "dop853_relative_energy_drift": ref_diag.get("relative_energy_drift"),
        "dop853_relative_angular_momentum_drift": ref_diag.get("relative_angular_momentum_drift"),
        "boundary": (
            "Pure point-mass Newtonian Sun/Jupiter/Saturn comparison. Velocity-Verlet is used as an independent fixed-step symplectic-style long-time comparator; "
            "DOP853 remains the adaptive reference implementation. This does not establish ephemeris accuracy, full relativistic dynamics, or observational validation."
        ),
    })


