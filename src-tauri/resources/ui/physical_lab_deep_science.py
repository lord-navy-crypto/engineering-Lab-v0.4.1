"""Deep-science extensions for Physical Lab simulation families.

This module adds bounded scientific studies that strengthen model content rather
than evidence/bridge plumbing:

- Kerr: distant-observer vacuum shadow critical curve from spherical photon
  orbit constants of motion.
- Sun/Jupiter/Saturn: fixed-step velocity-Verlet Newtonian comparator against
  the existing adaptive DOP853 baseline.
- Multilayer honeycomb lattice: microcanonical velocity-autocorrelation (VACF)
  and vibrational spectral-density study from a real time-domain trajectory.
- Numerical Error: a multi-mechanism atlas inspired by BetterBoard's independent
  finite-precision experiments, plus analysis of measured nonuniform time
  series without treating the finest measurement as physical truth.

All results are computational evidence with explicit scientific boundaries.
"""
from __future__ import annotations

