def _irregular_three_point_derivative(t0: float, t1: float, t2: float, y0: float, y1: float, y2: float) -> float:
    # Derivative of the degree-2 Lagrange interpolant evaluated at the middle timestamp t1.
    w0 = (t1 - t2) / ((t0 - t1) * (t0 - t2))
    w1 = (2.0 * t1 - t0 - t2) / ((t1 - t0) * (t1 - t2))
    w2 = (t1 - t0) / ((t2 - t0) * (t2 - t1))
    return float(w0 * y0 + w1 * y1 + w2 * y2)


def _trapz_float32(time_values: Any, values: Any, *, kahan: bool) -> float:
    np = _np()
    t = np.asarray(time_values, dtype=np.float32); y = np.asarray(values, dtype=np.float32)
    total = np.float32(0.0); compensation = np.float32(0.0)
    for i in range(len(t) - 1):
        area = np.float32(np.float32(0.5) * np.float32(y[i] + y[i + 1]) * np.float32(t[i + 1] - t[i]))
        if kahan:
            z = np.float32(area - compensation)
            updated = np.float32(total + z)
            compensation = np.float32((updated - total) - z)
            total = updated
        else:
            total = np.float32(total + area)
    return float(total)


def measured_series_numerics(
    time_s: Sequence[float], values: Sequence[float], *, downsample_factors: Iterable[int] = (2, 4, 8, 16)
) -> dict[str, Any]:
    """Analyze acquired samples without treating the finest series as physical truth."""
    np = _np()
    t = np.asarray(time_s, dtype=float); y = np.asarray(values, dtype=float)
    if t.ndim != 1 or y.ndim != 1 or len(t) != len(y) or len(t) < 7:
        raise ValueError("time_s and values must be paired 1D arrays with at least seven samples")
    if not (np.all(np.isfinite(t)) and np.all(np.isfinite(y))):
        raise ValueError("measured series contains non-finite values")
    dt = np.diff(t)
    if np.any(dt <= 0):
        raise ValueError("timestamps must be strictly increasing")
    median_dt = float(np.median(dt)); jitter = dt - median_dt
    full_integral = float(np.trapezoid(y, t))
    float32_naive = _trapz_float32(t, y, kahan=False)
    float32_kahan = _trapz_float32(t, y, kahan=True)
    derivative = np.full(len(t), np.nan, dtype=float)
    for i in range(1, len(t) - 1):
        derivative[i] = _irregular_three_point_derivative(t[i-1], t[i], t[i+1], y[i-1], y[i], y[i+1])
    rows = []
    for raw_factor in downsample_factors:
        factor = max(2, int(raw_factor))
        idx = np.arange(0, len(t), factor, dtype=int)
        if idx[-1] != len(t) - 1:
            idx = np.append(idx, len(t) - 1)
        if len(idx) < 4:
            continue
        tc = t[idx]; yc = y[idx]
        coarse_integral = float(np.trapezoid(yc, tc))
        coarse_derivative = np.asarray([
            _irregular_three_point_derivative(tc[i-1], tc[i], tc[i+1], yc[i-1], yc[i], yc[i+1])
            for i in range(1, len(tc) - 1)
        ])
        reference_derivative = derivative[idx[1:-1]]
        mask = np.isfinite(reference_derivative)
        derivative_rms_change = float(math.sqrt(float(np.mean((coarse_derivative[mask] - reference_derivative[mask]) ** 2)))) if np.any(mask) else None
        rows.append({
            "factor": factor,
            "samples": int(len(idx)),
            "integral": coarse_integral,
            "integral_change_vs_full_series": coarse_integral - full_integral,
            "derivative_rms_change_vs_full_series": derivative_rms_change,
        })
    unique = np.unique(y)
    observed_quantization_step = None
    if len(unique) > 1:
        differences = np.diff(np.sort(unique)); differences = differences[differences > 0]
        if differences.size:
            observed_quantization_step = float(np.min(differences))
    return _plain({
        "schema": "physical-lab-measured-series-numerics-v1",
        "sample_count": int(len(t)),
        "duration_s": float(t[-1] - t[0]),
        "median_dt_s": median_dt,
        "sample_rate_median_Hz": 1.0 / median_dt,
        "jitter_p95_abs_s": float(np.percentile(np.abs(jitter), 95)),
        "jitter_max_abs_s": float(np.max(np.abs(jitter))),
        "observed_min_value_step": observed_quantization_step,
        "float64_trapezoid": full_integral,
        "float32_naive_trapezoid": float32_naive,
        "float32_kahan_trapezoid": float32_kahan,
        "float32_naive_difference_vs_float64": float32_naive - full_integral,
        "float32_kahan_difference_vs_float64": float32_kahan - full_integral,
        "downsampling": rows,
        "time_s": t,
        "irregular_three_point_derivative": derivative,
        "boundary": (
            "The full measured series is an empirical numerical baseline, not exact physical ground truth. "
            "This study separates timestamp irregularity, downsampling, finite-difference sensitivity, accumulation precision, and observed value resolution; physical accuracy still requires calibration/reference evidence."
        ),
    })
