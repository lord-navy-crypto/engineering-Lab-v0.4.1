def _kerr_xi_eta(radius: float, spin: float) -> tuple[float, float]:
    r = float(radius)
    a = float(spin)
    if abs(a) < 1e-12 or abs(r - 1.0) < 1e-12:
        return float("nan"), float("nan")
    xi = (r**3 - 3.0 * r**2 + a * a * r + a * a) / (a * (1.0 - r))
    eta = r**3 * (4.0 * a * a - r * (r - 3.0) ** 2) / (a * a * (r - 1.0) ** 2)
    return float(xi), float(eta)


def kerr_shadow_curve(
    *, spin: float = 0.9, observer_inclination_deg: float = 60.0, samples: int = 900
) -> dict[str, Any]:
    """Return the Kerr vacuum shadow critical curve for an asymptotic observer.

    Celestial coordinates use the standard constants-of-motion mapping
      alpha = -xi / sin(theta_o)
      beta^2 = eta + a^2 cos^2(theta_o) - xi^2 cot^2(theta_o).
    The boundary is generated by unstable spherical photon orbits.  This is not
    a radiative-transfer image or an accretion-flow model.
    """
    np = _np()
    a = _finite(spin, "spin")
    inc = _finite(observer_inclination_deg, "observer inclination")
    if not (0.0 <= abs(a) < 1.0):
        raise ValueError("Kerr shadow requires |a/M| < 1")
    if not (0.5 <= inc <= 90.0):
        raise ValueError("observer inclination must be in [0.5, 90] degrees")
    count = max(180, min(int(samples), 4000))
    theta = math.radians(inc)
    if abs(a) < 1e-10:
        radius = math.sqrt(27.0)
        angles = np.linspace(0.0, 2.0 * math.pi, count, endpoint=True)
        alpha = radius * np.cos(angles)
        beta = radius * np.sin(angles)
        source_r = np.full(alpha.shape, 3.0)
    else:
        horizon = 1.0 + math.sqrt(1.0 - a * a)
        # All physical Kerr spherical photon radii lie inside this bounded scan.
        radii = np.linspace(horizon + 1e-5, 6.0, max(4 * count, 1600))
        upper: list[tuple[float, float, float]] = []
        sin_t = math.sin(theta)
        cos_t = math.cos(theta)
        cot2 = (cos_t / sin_t) ** 2
        for r in radii:
            xi, eta = _kerr_xi_eta(float(r), a)
            if not (math.isfinite(xi) and math.isfinite(eta)):
                continue
            beta2 = eta + a * a * cos_t * cos_t - xi * xi * cot2
            if beta2 < -1e-10:
                continue
            beta_value = math.sqrt(max(beta2, 0.0))
            upper.append((-xi / sin_t, beta_value, float(r)))
        if len(upper) < 30:
            raise RuntimeError("Kerr shadow scan did not resolve enough physical critical-curve points")
        # Order by image-plane alpha so the polygon closes deterministically.
        upper.sort(key=lambda row: row[0])
        # Bound payload size while preserving endpoints.
        if len(upper) > count:
            idx = np.linspace(0, len(upper) - 1, count).round().astype(int)
            upper = [upper[int(i)] for i in idx]
        lower = [(x, -y, r) for x, y, r in reversed(upper)]
        closed = upper + lower + [upper[0]]
        alpha = np.asarray([row[0] for row in closed], dtype=float)
        beta = np.asarray([row[1] for row in closed], dtype=float)
        source_r = np.asarray([row[2] for row in closed], dtype=float)

    alpha_min = float(np.min(alpha)); alpha_max = float(np.max(alpha))
    beta_min = float(np.min(beta)); beta_max = float(np.max(beta))
    area = 0.5 * abs(float(np.dot(alpha[:-1], beta[1:]) - np.dot(beta[:-1], alpha[1:])))
    if alpha[0] != alpha[-1] or beta[0] != beta[-1]:
        area += 0.5 * abs(float(alpha[-1] * beta[0] - beta[-1] * alpha[0]))
    centroid_shift = 0.5 * (alpha_min + alpha_max)
    return _plain({
        "schema": "physical-lab-kerr-shadow-v1",
        "spin_a_over_M": a,
        "observer_inclination_deg": inc,
        "alpha_over_M": alpha,
        "beta_over_M": beta,
        "spherical_photon_radius_over_M": source_r,
        "width_over_M": alpha_max - alpha_min,
        "height_over_M": beta_max - beta_min,
        "horizontal_midpoint_shift_over_M": centroid_shift,
        "critical_curve_area_over_M2": area,
        "alpha_extent_over_M": [alpha_min, alpha_max],
        "beta_extent_over_M": [beta_min, beta_max],
        "boundary": (
            "Asymptotic distant-observer critical curve in vacuum Kerr spacetime. "
            "It is the capture/escape boundary generated by unstable spherical photon orbits; "
            "it is not a synthetic telescope image and contains no emissivity, plasma, absorption, scattering, or instrument response."
        ),
    })


